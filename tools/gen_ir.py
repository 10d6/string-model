#!/usr/bin/env python3
"""Turn the CC0 library-mic impulse responses in data/ into a C++ header.

    python3 tools/gen_ir.py data/violin violin src/ir/ViolinIR.h
    python3 tools/gen_ir.py data/cello cello src/ir/CelloIR.h --iowa

(An optional 4th argument is the files' prefix; default <name>_solo.)

The violin's IRs come from 10d6/instrument-research (data/library_mic_responses),
derived from VSCO-2-CE (Versilian Studios, CC0). --iowa: the cello's, fitted
here from the University of Iowa MIS arco (anechoic, "free of restrictions")
with instrument-research's body_response.py and export_ir.py (docs/MODEL.md).
"""
import sys, os
import numpy as np
from scipy.io import wavfile

iowa = "--iowa" in sys.argv
argv = [a for a in sys.argv[1:] if a != "--iowa"]
src, name, out = argv[0:3]
prefix = argv[3] if len(argv) > 3 else name + "_solo"
parts = []
for kind in ("left", "right", "mono_smooth"):
    path = os.path.join(src, f"{prefix}_ir_{kind}_48000.wav")
    sr, x = wavfile.read(path)
    assert sr == 48000
    x = np.asarray(x, dtype=np.float32)
    # Trim the silent tail.
    nz = np.nonzero(np.abs(x) > 1e-5 * np.abs(x).max())[0]
    x = x[: nz[-1] + 1]
    parts.append((kind, x))
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as f:
    if iowa:
        f.write("// Generated by tools/gen_ir.py from data/%s: fitted from the University of Iowa\n" % os.path.basename(src))
        f.write("// MIS recordings (free of restrictions; instrument-research body_response.py). Do not edit.\n#pragma once\n\n")
    else:
        f.write("// Generated by tools/gen_ir.py from data/%s (CC0, derived from VSCO-2-CE,\n" % os.path.basename(src))
        f.write("// Versilian Studios, via 10d6/instrument-research). Do not edit.\n#pragma once\n\n")
    f.write("namespace sm::ir {\n\nconstexpr int k%sRate = 48000;\n" % name.capitalize())
    for kind, x in parts:
        ident = "k" + name.capitalize() + "".join(w.capitalize() for w in kind.split("_"))
        f.write("constexpr int %sLen = %d;\n" % (ident, len(x)))
        f.write("constexpr float %s[%d] = {\n" % (ident, len(x)))
        for i in range(0, len(x), 8):
            f.write("  " + ", ".join("%.9gf" % v for v in x[i:i + 8]) + ",\n")
        f.write("};\n")
    f.write("\n}  // namespace sm::ir\n")
print("wrote", out, [(k, len(x)) for k, x in parts])
