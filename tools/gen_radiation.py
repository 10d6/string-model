#!/usr/bin/env python3
"""Turn data/<instrument>/radiation_target.csv into model/data/<Name>Radiation.h.

    python3 tools/gen_radiation.py data/violin/radiation_target.csv Violin model/data/ViolinRadiation.h
    python3 tools/gen_radiation.py data/cello/radiation_target.csv Cello model/data/CelloRadiation.h --library
(--library: a target from the library curve alone, combine_target.py with "-".)
"""
import sys
import numpy as np
src, name, out = sys.argv[1:4]
t = np.genfromtxt(src, delimiter=',', names=True)
with open(out, 'w') as f:
    f.write("// Generated by tools/gen_radiation.py from %s (tools/combine_target.py):\n" % src)
    f.write("// the %s's bridge force -> recording target, dB on a 1/24-octave grid.\n" % name.lower())
    f.write("// Derived from VSCO-2-CE (Versilian Studios, CC0)%s.\n// Do not edit; regenerate.\n#pragma once\n\nnamespace sm::data {\n\n" % ("" if "--library" in sys.argv else " and this synth's own renders"))
    f.write("constexpr int k%sRadiationCount = %d;\n" % (name, len(t)))
    f.write("constexpr float k%sRadiationHz[%d] = {\n" % (name, len(t)))
    for i in range(0, len(t), 8): f.write("  " + ", ".join("%.1ff" % v for v in t['freq_hz'][i:i+8]) + ",\n")
    f.write("};\nconstexpr float k%sRadiationDb[%d] = {\n" % (name, len(t)))
    for i in range(0, len(t), 8): f.write("  " + ", ".join("%.2ff" % v for v in t['target_db'][i:i+8]) + ",\n")
    f.write("};\n\n}  // namespace sm::data\n")
